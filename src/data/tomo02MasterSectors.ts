// Flat searchable item for Global Search
export interface SearchableItem {
  id?: string;
  sectorNumber: string;
  sectorTitle: string;
  title: string;
  type: 'SECTOR' | 'INVESTIGATION' | 'LAB' | 'ARTEFACT' | 'CATEGORY' | 'METHODOLOGY';
  matchContext: string;
}

export const getAllSearchableItems = (): SearchableItem[] => {
  const items: SearchableItem[] = [];

  TOMO_02_MASTER_SECTORS.forEach((sec) => {
    // Sector title & subtitle
    items.push({
      sectorNumber: sec.sectorNumber,
      sectorTitle: sec.title,
      title: sec.title,
      type: 'SECTOR',
      matchContext: `${sec.title} ${sec.subtitle}`,
    });

    // Investigations
    sec.investigationsList.forEach((inv) => {
      items.push({
        id: inv.id,
        sectorNumber: sec.sectorNumber,
        sectorTitle: sec.title,
        title: inv.title,
        type: 'INVESTIGATION',
        matchContext: `${inv.id} ${inv.title} ${sec.title}`,
      });
    });

    // Artefact / Lab
    if (sec.artefactOrLab) {
      items.push({
        sectorNumber: sec.sectorNumber,
        sectorTitle: sec.title,
        title: sec.artefactOrLab,
        type: sec.artefactOrLab.includes('Lab') ? 'LAB' : 'ARTEFACT',
        matchContext: sec.artefactOrLab,
      });
    }

    // Categories (Sector 37)
    if (sec.categories) {
      sec.categories.forEach((cat) => {
        items.push({
          sectorNumber: sec.sectorNumber,
          sectorTitle: sec.title,
          title: `Categoría: ${cat}`,
          type: 'CATEGORY',
          matchContext: `Categoría ${cat} ${sec.title}`,
        });
      });
    }

    // Methodology (Sector 37, 39)
    if (sec.methodology) {
      items.push({
        sectorNumber: sec.sectorNumber,
        sectorTitle: sec.title,
        title: sec.methodology,
        type: 'METHODOLOGY',
        matchContext: sec.methodology,
      });
    }
  });

  return items;
};
