export function getGlossaryTerm(key: string): TutorGlossaryTerm | null {
  const cleanKey = key.toLowerCase().replace(/[^a-z0-9_]/g, '');
  return TUTOR_GLOSSARY_TERMS[cleanKey] || TUTOR_GLOSSARY_TERMS[key] || null;
}

export function searchGlossary(query: string): TutorGlossaryTerm[] {
  if (!query || query.trim() === '') {
    return Object.values(TUTOR_GLOSSARY_TERMS);
  }
  const q = query.toLowerCase().trim();
  return Object.values(TUTOR_GLOSSARY_TERMS).filter((t) => {
    return (
      t.term.toLowerCase().includes(q) ||
      t.shortDef.toLowerCase().includes(q) ||
      t.simple.toLowerCase().includes(q) ||
      t.category.toLowerCase().includes(q) ||
      t.example.toLowerCase().includes(q)
    );
  });
}
